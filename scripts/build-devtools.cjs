// No bundler dependencies. Userscript source remains the shared runtime source.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const source = read('userscript/boba.user.js');
const begin = '  // BEGIN SHARED RUNTIME — scripts/build-devtools.cjs reuses this exact source.\n';
const end = '  // END SHARED RUNTIME';
const start = source.indexOf(begin);
const stop = source.indexOf(end);
if (start < 0 || stop < start || source.indexOf(begin, start + 1) >= 0) throw new Error('Shared runtime markers missing or ambiguous');
const body = source.slice(start + begin.length, stop);
const runtime = `(() => {\n'use strict';\n${body}\nreturn { Agent, ProgressLedger, ToolDispatchError, TOOLS, createPageTools, bounded, trimContext, interruptedResults, mountPanel };\n})()`;
const banner = '// Generated by scripts/build-devtools.cjs. Edit source files, then npm run build:devtools.\n';
const outputs = {
  'devtools/runtime.js': `${banner}globalThis.BobaRuntime = ${runtime};\n`,
  'devtools/boba-snippet.js': `${banner}// Paste this entire file into Chrome DevTools > Sources > Snippets.\n(() => {\n'use strict';\n// Change only this origin if your server uses a different loopback port.\nconst BOBA_SERVER_ORIGIN = 'http://127.0.0.1:8787';\nconst runtime = ${runtime};\n${read('devtools/bridge.js')}\n${read('devtools/snippet-entry.js')}\nstartBobaSnippet(runtime, createBobaPeer, BOBA_SERVER_ORIGIN);\n})();\n//# sourceURL=boba-devtools-snippet.js\n`,
};
for (const [name, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(path.join(root, name)) || read(name) !== content) {
      console.error(`${name} is stale; run npm run build:devtools`);
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(path.join(root, name), content);
    console.log(`Built ${name}`);
  }
}
